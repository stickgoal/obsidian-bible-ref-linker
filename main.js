function buildDecorations(view, app, onHover) {
  if (view.state.field(import_obsidian2.editorLivePreviewField, false) !== true)
    return import_view.Decoration.none;
  const doc = view.state.doc;
  const selection = view.state.selection;
  const activeLines = new Set(selection.ranges.map((r) => doc.lineAt(r.head).number));
  const prot = protectedRanges(doc.toString());
  const widgets = [];
  for (const { from, to } of view.visibleRanges) {
    const text = view.state.sliceDoc(from, to);
    const wiki = wikilinkRanges(text);
    for (const ref of matchRefs(text)) {
      for (const seg of ref.segments) {
        if (!seg.book || !seg.chapter || !seg.verseStart)
          continue;
        const start = from + seg.start;
        const end = from + seg.end;
        if (prot.some(([x, y]) => start < y && end > x))
          continue;
        if (!activeLines.has(doc.lineAt(start).number))
          continue;
        if (selection.ranges.some((r) => r.to >= start && r.from <= end))
          continue;
        if (wiki.some(([a, b]) => seg.start < b && seg.end > a))
          continue;
        widgets.push(
          import_view.Decoration.replace({
            widget: new BibleLinkWidget(
              app,
              seg.target,
              text.slice(seg.start, seg.end),
              segRange(seg),
              onHover
            )
          }).range(start, end)
        );
      }
    }
  }
  return import_view.Decoration.set(widgets, true);
}
function bibleRefEditorExtension(app, onHover) {
  return import_view.ViewPlugin.fromClass(
    class {
      constructor(view) {
        this.view = view;
        this.decorations = buildDecorations(view, app, onHover);
      }
      update(_update) {
        this.decorations = buildDecorations(this.view, app, onHover);
      }
    },
    { decorations: (v) => v.decorations }
  );
}

